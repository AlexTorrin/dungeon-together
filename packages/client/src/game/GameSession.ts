import type { Command, GameEvent, GameState } from '@dt/shared';

/** Получает события хода и состояние, к которому они привели. */
export type SessionListener = (events: readonly GameEvent[], state: GameState) => void;

/**
 * Абстракция «игры» для сцены. Сцена не знает, локальная это игра или сетевая:
 * она шлёт команды и проигрывает события, которые приходят по подписке.
 *
 * Ответ на send() всегда приходит позже и только через подписчиков — так же, как
 * по сети. Чужие события (другой игрок выбрал действие) приходят без всякого send().
 * Сейчас есть только LocalGame; на шаге 6 появится реализация поверх Colyseus.
 */
export interface GameSession {
  /** Последнее известное состояние: обновляется вместе с доставкой событий. */
  readonly state: GameState;
  /** Отправить намерение. Результат придёт подписчикам; невалидная команда — без событий. */
  send(command: Command): void;
  /** Подписаться на события. Возвращает функцию отписки. */
  subscribe(listener: SessionListener): () => void;
}
